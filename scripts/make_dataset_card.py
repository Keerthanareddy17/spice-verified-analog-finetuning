"""Write docs/DATASET_CARD.md and data/samples/phase2_examples.jsonl from a built dataset."""
import argparse
import json

from analogft import paths
from analogft.dataset import read_jsonl, write_jsonl


def pick_samples(train: list[dict]) -> list[dict]:
    """5 deterministic examples: distinct labels, steps 0,0,1,2,3 where available."""
    out, used = [], set()
    for step in (0, 0, 1, 2, 3):
        for r in sorted(train, key=lambda r: r["id"]):
            if r["step_index"] == step and r["label_action"] not in used and r["best_improves"]:
                out.append(r); used.add(r["label_action"]); break
    return out


def table(rows: list[list], header: list[str]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def dist_row(name: str, d: dict, f: str = ".3f") -> list:
    return [name] + [format(d[k], f) for k in ("min", "p5", "median", "p95", "max", "mean")]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", default="phase2")
    args = ap.parse_args()
    d = paths.DATA_DIR / args.name
    train = read_jsonl(d / "train.jsonl")
    st = json.loads((d / "build_stats.json").read_text())
    s, cfg = st["summary"], st["config"]
    bl = json.loads((paths.RESULTS_DIR / "phase2_baselines.json").read_text())
    write_jsonl(paths.DATA_DIR / "samples" / "phase2_examples.jsonl", pick_samples(train))

    n = s["n_states"]
    allrecs = train + read_jsonl(d / "val.jsonl") + read_jsonl(d / "test.jsonl")
    ties = [r for r in allrecs if r["tied_best"]]
    tie_solve = sum(r["label_solves"] for r in ties) / max(1, len(ties))
    labels = [[a, c, f"{100 * c / n:.1f}%"] for a, c in s["label_counts"].items()]
    cols = [("valid_rate", "valid"), ("top1", "top-1 (tie-aware)"), ("top1_exact", "top-1 (exact id)"),
            ("top3", "top-3"), ("improve_rate", "improve rate"), ("mean_regret", "mean regret")]
    base = {}
    for split in ("val", "test"):
        base[split] = table([[b.replace("_", " ")] + [f"{bl[b][split][k]:.3f}" for k, _ in cols]
                             for b in ("random", "majority", "textbook_rules")], ["baseline"] + [c for _, c in cols])
    md = f"""# Dataset card: Phase 2 (simulator-labeled action choices)

Generated by `scripts/build_dataset.py --config configs/phase2.json` (seed {cfg['seed']}). Circuit: two-stage
Miller op-amp, Level-1 models (see DECISIONS.md D1). Every label comes from ngspice, never from a person or a model.

## How it was made
1. **Targets.** {st['n_targets']} random designs (each knob log-uniform in [nominal/3, nominal*3], clipped to bounds),
   kept if the simulation was ok, every device saturated and PM >= {cfg['target_min_pm']:.0f} deg
   ({st['n_targets']} of {st['target_candidates']} candidates kept).
2. **Specs.** Taken from each target's own metrics with slack (gain -U(0,3) dB, UGF x U(0.75,0.95),
   PM -U(0,10) clamped to [45,70], power x U(1.05,1.3)). The target meets its spec, so every spec is achievable.
3. **Start states.** The 7 action knobs of a target are multiplied by 1.3^k (k integer in [-3,3], sum |k| in [2,6],
   no knob allowed to hit a bound). Kept if the sim ran, the spec fails and spec_distance <= {cfg['max_start_distance']:.0f}.
   Of {st['start_candidates']} candidates: {st['start_rejected']['already_pass']} already passed the spec,
   {st['start_rejected']['failed_sim']} failed to simulate, {st['start_rejected']['too_far']} were too far.
   Each start is at most {cfg['k_total_max']} inverse moves from its target.
4. **Labeling.** For every state all available actions are simulated; improvement = distance_before - distance_after;
   label = best action (ties: lowest action-id order). Then the greedy best action is followed for up to
   {cfg['extra_steps']} more steps (stopping when the spec is met or nothing improves), labeling each visited state.
5. **Splits** by target (group_id), 80/10/10, seed {cfg['seed']}; asserted leak-free.

## Size and cost
- Labeled states: **{n}** from {s['n_episodes']} start states / {st['n_targets']} targets.
- Per split (states / episodes / targets): {', '.join(f"{k}: {s['states_per_split'].get(k, 0)} / {s['episodes_per_split'].get(k, 0)} / {s['groups_per_split'].get(k, 0)}" for k in ('train', 'val', 'test'))}.
- Unique simulations requested: **{st['unique_simulations']}** ({st['unique_simulations'] / n:.1f} per labeled state),
  of which {st['cache_hits']} came from the cache. Simulation wall time {st['simulation_seconds']} s, whole build {st['total_seconds']} s.

## Label distribution (best action)
{table(labels, ['action', 'count', 'share'])}

Most frequent label share: **{100 * s['top_label_fraction']:.1f}%**{' (imbalanced)' if s['top_label_fraction'] > 0.25 else ''}.
Ties for best action: {100 * s['tie_fraction']:.1f}% of states ({100 * tie_solve:.0f}% of those ties are several actions that each fully solve the spec); the stored
label is the lowest action id among them, so **use tie-aware scoring** (`analogft.evaluation`).

## Quality numbers
- States whose best action improves spec distance (`best_improves`): **{100 * s['best_improves_fraction']:.1f}%**.
- States where the best action fully solves the spec in one move (`label_solves`): {100 * s['label_solves_fraction']:.1f}%.
- Across all {int(s['actions_per_state']['mean'] * n)} simulated action outcomes: {100 * s['improving_action_fraction']:.1f}% improve the distance,
  {100 * s['unsaturated_action_fraction']:.1f}% leave a device out of saturation, {100 * s['failed_sim_action_fraction']:.2f}% have no complete metrics.
- Step index counts: {', '.join(f'step {k}: {v}' for k, v in s['step_index_counts'].items())}.

{table([dist_row('spec_distance (all labeled states)', s['distance']), dist_row('spec_distance (start states)', s['start_distance']), dist_row('improvement (every action)', s['improvement_all_actions'])], ['quantity', 'min', 'p5', 'median', 'p95', 'max', 'mean'])}

## Prompt size (4 characters per token, rough)
{table([dist_row('user message', s['user_tokens'], '.0f'), dist_row('system + user', s['system_plus_user_tokens'], '.0f'), dist_row('assistant reply', s['assistant_tokens'], '.0f')], ['text', 'min', 'p5', 'median', 'p95', 'max', 'mean'])}

Longest generated reason: {s['assistant_words_max']} words.

## Baselines (no GPU, lookup scoring)
Majority action (most frequent train label): `{bl['_majority_action']}`. Random is the exact expectation, not a sample.
"valid" counts picks that are available at that state; an invalid pick is scored as a no-move.

**Validation** (n={bl['random']['val']['n']})

{base['val']}

**Test** (n={bl['random']['test']['n']})

{base['test']}

## Files (data/{args.name}/)
`train|val|test.jsonl` (one labeled state per line: id, group_id, split, step_index, spec, design, metrics, regions,
available_actions, messages[system,user,assistant], label_action, best_improves, label_solves, tied_best, ranking,
action_outcomes), `episodes_*.jsonl` (target + spec + start design per start state, for the Phase 4 agent),
`build_stats.json`. `data/samples/phase2_examples.jsonl` holds 5 committed examples.

## Limitations
- Level-1 device models, one fixed load and supply (see DECISIONS.md D1, D2).
- Only the 7 lattice knobs can move; 4 other knobs stay at the target's value.
- Labels are one-step greedy (best immediate improvement), not the best multi-step plan.
- Spec distance is a hand-weighted sum (D7); a different weighting could change the labels.
"""
    out = paths.REPO_ROOT / "docs" / "DATASET_CARD.md"
    out.write_text(md)
    print("wrote", out, "and samples:", len(pick_samples(train)))


if __name__ == "__main__":
    main()
